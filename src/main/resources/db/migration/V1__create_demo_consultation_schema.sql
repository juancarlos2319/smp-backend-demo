CREATE TABLE demo_employees (
    id INTEGER PRIMARY KEY,
    rfc VARCHAR(13) NOT NULL UNIQUE,
    curp VARCHAR(18) NOT NULL UNIQUE,
    full_name VARCHAR(160) NOT NULL,
    active BOOLEAN NOT NULL,
    details JSONB NOT NULL
);

CREATE TABLE demo_work_centers (
    code VARCHAR(10) PRIMARY KEY,
    name VARCHAR(180) NOT NULL,
    level_name VARCHAR(80),
    shift_name VARCHAR(80),
    locality VARCHAR(120),
    municipality VARCHAR(120),
    status_id INTEGER NOT NULL,
    status_name VARCHAR(40) NOT NULL,
    details JSONB NOT NULL
);

CREATE TABLE demo_categories (
    code VARCHAR(12) PRIMARY KEY,
    description VARCHAR(180) NOT NULL,
    model_id INTEGER NOT NULL,
    details JSONB NOT NULL
);

CREATE TABLE demo_concepts (
    perc_ded CHAR(1) NOT NULL CHECK (perc_ded IN ('P', 'D')),
    code VARCHAR(12) NOT NULL,
    description VARCHAR(180) NOT NULL,
    details JSONB NOT NULL,
    PRIMARY KEY (perc_ded, code)
);

CREATE TABLE demo_positions (
    id INTEGER PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    category_code VARCHAR(12) NOT NULL REFERENCES demo_categories(code),
    center_code VARCHAR(10) NOT NULL REFERENCES demo_work_centers(code),
    hours INTEGER,
    status_id INTEGER NOT NULL,
    status_name VARCHAR(40) NOT NULL,
    unit_code VARCHAR(8),
    subunit_code VARCHAR(8),
    jornada_hours INTEGER,
    max_week_hours INTEGER,
    max_class_hours INTEGER,
    summary JSONB NOT NULL,
    details JSONB NOT NULL,
    compatibility JSONB NOT NULL
);

CREATE TABLE demo_position_occupants (
    position_id INTEGER NOT NULL REFERENCES demo_positions(id),
    employee_id INTEGER NOT NULL REFERENCES demo_employees(id),
    status_id INTEGER,
    status_name VARCHAR(40),
    salary_level INTEGER,
    employee_position JSONB NOT NULL,
    occupant JSONB NOT NULL,
    PRIMARY KEY (position_id, employee_id)
);

CREATE TABLE demo_movement_history (
    id INTEGER PRIMARY KEY,
    employee_id INTEGER REFERENCES demo_employees(id),
    position_id INTEGER REFERENCES demo_positions(id),
    center_code VARCHAR(10),
    data JSONB NOT NULL
);

CREATE TABLE demo_category_concepts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_code VARCHAR(12) NOT NULL REFERENCES demo_categories(code),
    data JSONB NOT NULL
);

CREATE INDEX demo_employee_name_idx ON demo_employees (lower(full_name));
CREATE INDEX demo_position_category_idx ON demo_positions (category_code);
CREATE INDEX demo_position_center_idx ON demo_positions (center_code);
CREATE INDEX demo_history_employee_idx ON demo_movement_history (employee_id);
CREATE INDEX demo_history_position_idx ON demo_movement_history (position_id);

