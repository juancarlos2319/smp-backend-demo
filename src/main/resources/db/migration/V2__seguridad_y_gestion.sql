-- Usuarios, roles, módulos y etapas del flujo FUP (equivalente demo de core_* y fup_etapa_roles del back real).
-- Las contraseñas se dejan en NULL: DemoSeedPasswords las llena al arrancar con demo.seed.password.

CREATE TABLE cat_nivel_rh (
    id INTEGER PRIMARY KEY,
    nivel VARCHAR(80) NOT NULL
);

CREATE TABLE core_icons (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    icon VARCHAR(80),
    material_icon VARCHAR(80)
);

CREATE TABLE core_modules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(60) NOT NULL,
    name VARCHAR(120) NOT NULL,
    path VARCHAR(200),
    description VARCHAR(255),
    vista BOOLEAN NOT NULL DEFAULT TRUE,
    parent_id INTEGER REFERENCES core_modules(id),
    icon_id INTEGER REFERENCES core_icons(id),
    orden SMALLINT,
    todos_movimientos BOOLEAN NOT NULL DEFAULT FALSE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX core_modules_codigo_uk ON core_modules (codigo) WHERE NOT deleted;

-- Movimientos de FUP que cubre un módulo; sin motivo, todos los motivos del movimiento
CREATE TABLE core_module_movimientos (
    module_id INTEGER NOT NULL REFERENCES core_modules(id),
    cve_movimiento CHAR(2) NOT NULL,
    cve_motivo CHAR(2)
);

CREATE TABLE core_roles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(255),
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE core_role_modules (
    role_id INTEGER NOT NULL REFERENCES core_roles(id),
    module_id INTEGER NOT NULL REFERENCES core_modules(id),
    can_agregar BOOLEAN NOT NULL DEFAULT FALSE,
    can_editar BOOLEAN NOT NULL DEFAULT FALSE,
    can_eliminar BOOLEAN NOT NULL DEFAULT FALSE,
    can_autorizar BOOLEAN NOT NULL DEFAULT FALSE,
    can_ver_detalle_tecnico BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (role_id, module_id)
);

CREATE TABLE fup_etapas (
    etapa VARCHAR(30) PRIMARY KEY,
    orden INTEGER NOT NULL UNIQUE,
    opcional BOOLEAN NOT NULL
);

CREATE TABLE fup_etapa_roles (
    role_id INTEGER NOT NULL REFERENCES core_roles(id),
    etapa VARCHAR(30) NOT NULL REFERENCES fup_etapas(etapa),
    PRIMARY KEY (role_id, etapa)
);

CREATE TABLE core_users (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(120) NOT NULL,
    email VARCHAR(160),
    password_hash VARCHAR(100),
    area INTEGER REFERENCES cat_nivel_rh(id),
    task VARCHAR(160),
    cat_empleado_id INTEGER,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    principal VARCHAR(200),
    is_verified BOOLEAN NOT NULL DEFAULT TRUE,
    is_password BOOLEAN NOT NULL DEFAULT TRUE,
    deleted BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX core_users_username_uk ON core_users (lower(username)) WHERE NOT deleted;

CREATE TABLE core_user_roles (
    user_id INTEGER NOT NULL REFERENCES core_users(id),
    role_id INTEGER NOT NULL REFERENCES core_roles(id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE core_user_extras (
    user_id INTEGER NOT NULL REFERENCES core_users(id),
    module_id INTEGER NOT NULL REFERENCES core_modules(id),
    PRIMARY KEY (user_id, module_id)
);

CREATE TABLE core_verification_codes (
    user_id INTEGER PRIMARY KEY REFERENCES core_users(id),
    code VARCHAR(6) NOT NULL,
    expires_at TIMESTAMP NOT NULL
);

CREATE TABLE core_password_recovery (
    folio VARCHAR(64) PRIMARY KEY,
    ts VARCHAR(20) NOT NULL,
    user_id INTEGER NOT NULL REFERENCES core_users(id),
    expires_at TIMESTAMP NOT NULL,
    used BOOLEAN NOT NULL DEFAULT FALSE
);

